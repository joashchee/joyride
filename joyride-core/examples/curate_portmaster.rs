//! Adds PortMaster's LÖVE ports to data/games.toml (merged and de-duplicated
//! with what is there). Reads a PortMaster-New checkout's `port.json` and
//! launch scripts; nothing is downloaded or run.
//!
//!   cargo run --manifest-path joyride-core/Cargo.toml --example curate_portmaster -- DIR
//!
//! DIR is a PortMaster-New checkout (a shallow, blob-less sparse clone of
//! `ports/*/*.sh` and `ports/*/port.json` is enough: scripts/check-portmaster.py
//! shows the commands). Without DIR it makes that clone in a temporary folder
//! (needs git and github.com).

use joyride_core::games::{from_portmaster, Added, Catalogue};
use std::path::{Path, PathBuf};
use std::process::Command;

fn runtime_of(script: &str) -> Option<String> {
    let i = script.find("runtimes/")? + "runtimes/".len();
    let rest = script[i..].trim_start_matches('"');
    let name: String = rest.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '.').collect();
    name.starts_with("love_").then_some(name)
}

fn clone() -> PathBuf {
    let d = std::env::temp_dir().join("joyride-portmaster-new");
    let _ = std::fs::remove_dir_all(&d);
    let git = |args: &[&str], dir: Option<&Path>| {
        let mut c = Command::new("git");
        c.args(["-c", "protocol.ext.allow=never", "-c", "core.hooksPath=/dev/null"]).args(args).env("GIT_TERMINAL_PROMPT", "0");
        if let Some(d) = dir {
            c.current_dir(d);
        }
        assert!(c.status().expect("git").success(), "git {args:?} failed");
    };
    git(&["clone", "-q", "--depth", "1", "--filter=blob:none", "--sparse", "https://github.com/PortsMaster/PortMaster-New", d.to_str().unwrap()], None);
    git(&["sparse-checkout", "set", "--no-cone", "/ports/*/*.sh", "/ports/*/port.json"], Some(&d));
    d
}

fn main() {
    let repo = std::env::args().nth(1).map(PathBuf::from).unwrap_or_else(clone);
    let data = Path::new(env!("CARGO_MANIFEST_DIR")).join("data/games.toml");
    let mut cat = Catalogue::parse(&std::fs::read_to_string(&data).unwrap()).unwrap();
    let today = Command::new("date").arg("+%Y-%m-%d").output().ok().map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string()).unwrap_or_default();
    let mut dirs: Vec<_> = std::fs::read_dir(repo.join("ports")).expect("no ports/ folder: not a PortMaster-New checkout").flatten().map(|e| e.path()).filter(|p| p.is_dir()).collect();
    dirs.sort();
    let (mut added, mut merged) = (0, 0);
    for d in dirs {
        // A LÖVE port sources a love runtime (or runs $LOVE_RUN).
        let rt = std::fs::read_dir(&d).into_iter().flatten().flatten().filter(|f| f.path().extension().is_some_and(|x| x == "sh")).find_map(|f| {
            let t = std::fs::read_to_string(f.path()).ok()?;
            runtime_of(&t).or_else(|| t.contains("$LOVE_RUN").then(|| "love".to_string()))
        });
        let Some(rt) = rt else { continue };
        let Ok(text) = std::fs::read_to_string(d.join("port.json")) else { continue };
        let Ok(port) = serde_json::from_str::<serde_json::Value>(&text) else { continue };
        let folder = d.file_name().unwrap().to_string_lossy().to_string();
        let Some(e) = from_portmaster(&port, &folder, Some(&rt).filter(|r| r.starts_with("love_")).map(|r| r.as_str()), &today) else { continue };
        match cat.add(e) {
            Added::New(_) => added += 1,
            Added::Merged(id) => {
                merged += 1;
                println!("{folder}: merged into {id}");
            }
        }
    }
    let n = cat.dedupe();
    for l in &cat.lookalikes {
        println!("look-alike, left apart: {} and {}", l.id, l.other);
    }
    cat.generated = today;
    cat.entries.sort_by(|a, b| a.id.cmp(&b.id));
    let header = "# The LÖVE games and apps catalogue (docs/love-games-library.md). Generated by\n# `curate_games` and `curate_portmaster` (cargo run --manifest-path joyride-core/Cargo.toml --example ...); merged by the rules in src/games.rs.\n";
    std::fs::write(&data, format!("{header}{}", cat.to_toml())).unwrap();
    println!("{added} ports added, {merged} merged into existing entries, {n} merged after; {} entries", cat.entries.len());
}
