//! The generated `_jr_shim.lua` for each target (spec 4C), and the
//! controller map for PortMaster. The shim is installed by a three-line
//! wrapper `main.lua` (see `overlay`): it is required before the game's own
//! main and `jr.install()` runs after, once the game has defined its
//! callbacks, so the shim can wrap them.

use crate::scan::{Scan, Target};

#[derive(Debug, Clone, PartialEq)]
pub struct Config {
    pub target: Target,
    pub design_w: u32,
    pub design_h: u32,
    pub integer_scale: bool,
    /// Game uses the mouse: PortMaster gets a stick-driven cursor.
    pub virtual_mouse: bool,
    /// Game uses the keyboard but not touch: mobile gets an on-screen pad.
    pub touch_overlay: bool,
    pub pad: PadKeys,
}

/// The keys the touch pad presses, chosen from the keys the game reads.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PadKeys {
    pub left: String,
    pub right: String,
    pub up: String,
    pub down: String,
    pub a: String,
    pub b: String,
    pub start: String,
}

const ACTION_PREFERENCE: [&str; 8] = ["z", "x", "space", "return", "c", "v", "lctrl", "lshift"];

impl PadKeys {
    /// Arrow keys unless the game reads only WASD; action keys from the
    /// game's own, then common defaults.
    pub fn from_keys(keys: &std::collections::BTreeSet<String>) -> PadKeys {
        let has = |k: &str| keys.contains(k);
        let wasd = ["w", "a", "s", "d"].iter().all(|k| has(k)) || (["w", "a", "s", "d"].iter().filter(|k| has(k)).count() >= 2 && !["up", "down", "left", "right"].iter().any(|k| has(k)));
        let (left, right, up, down) = if wasd { ("a", "d", "w", "s") } else { ("left", "right", "up", "down") };
        let movement = [left, right, up, down];
        let mut actions: Vec<&str> = ACTION_PREFERENCE.iter().copied().filter(|k| has(k) && !movement.contains(k)).collect();
        for k in ACTION_PREFERENCE {
            if !actions.contains(&k) {
                actions.push(k);
            }
        }
        let start = if has("escape") && !has("return") { "escape" } else { "return" };
        PadKeys {
            left: left.into(),
            right: right.into(),
            up: up.into(),
            down: down.into(),
            a: actions[0].into(),
            b: actions.iter().find(|k| **k != actions[0] && **k != start).copied().unwrap_or("x").into(),
            start: start.into(),
        }
    }
}

impl Config {
    /// A config from a scan and the game's design size (its window size).
    pub fn from_scan(target: Target, scan: &Scan) -> Config {
        let w = scan.window.width.unwrap_or(800.0).max(1.0) as u32;
        let h = scan.window.height.unwrap_or(600.0).max(1.0) as u32;
        Config {
            target,
            design_w: w,
            design_h: h,
            integer_scale: target == Target::PortMaster,
            virtual_mouse: target == Target::PortMaster && scan.mouse,
            touch_overlay: target == Target::Mobile && scan.keyboard && !scan.touch,
            pad: PadKeys::from_keys(&scan.keys),
        }
    }
}

fn lua_str(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c if c.is_control() => o.push(' '),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// The Lua source of `_jr_shim.lua`.
pub fn generate(c: &Config) -> String {
    let target = match c.target {
        Target::PortMaster => "portmaster",
        Target::Mobile => "mobile",
        Target::Web => "web",
    };
    let mut s = String::new();
    s.push_str(&format!("-- _jr_shim.lua: generated by JoyrIDE for the {target} build. Do not edit; change .joyride/patches/{target}/ instead.\n"));
    match c.target {
        Target::Web => s.push_str(WEB),
        _ => {
            s.push_str(&COMMON.replace("@DW@", &c.design_w.to_string()).replace("@DH@", &c.design_h.to_string()).replace("@INT@", if c.integer_scale { "true" } else { "false" }).replace("@TARGET@", &lua_str(target)));
            if c.target == Target::PortMaster {
                s.push_str(&PORTMASTER.replace("@VMOUSE@", if c.virtual_mouse { "true" } else { "false" }));
            }
            if c.touch_overlay {
                let p = &c.pad;
                s.push_str(
                    &TOUCH
                        .replace("@LEFT@", &lua_str(&p.left))
                        .replace("@RIGHT@", &lua_str(&p.right))
                        .replace("@UP@", &lua_str(&p.up))
                        .replace("@DOWN@", &lua_str(&p.down))
                        .replace("@A@", &lua_str(&p.a))
                        .replace("@B@", &lua_str(&p.b))
                        .replace("@START@", &lua_str(&p.start)),
                );
            }
            s.push_str(FINISH);
        }
    }
    s
}

/// The `main.lua` wrapper: the shim first, the game's own main, then install.
pub fn main_wrapper(target: &str) -> String {
    main_wrapper_with(target, false)
}

/// The wrapper for a build that also carries `_jr_compat.lua` (the 11.5
/// variant of a 12.0 game): the compat functions are defined before anything else.
pub fn main_wrapper_with(target: &str, compat: bool) -> String {
    let pre = if compat { "require(\"_jr_compat\")\n" } else { "" };
    format!("-- main.lua written by JoyrIDE for the {target} build; the project's own is _orig_main.lua.\n{pre}local jr = require(\"_jr_shim\")\nrequire(\"_orig_main\")\njr.install()\n")
}

const COMMON: &str = r#"
-- A headless run (tests, servers: no window or graphics module) has nothing to scale.
if not (love.graphics and love.mouse) then
  return { target = @TARGET@, headless = true, hooks = {}, install = function() end }
end
local jr = { target = @TARGET@, dw = @DW@, dh = @DH@, integer = @INT@, hooks = {} }
local lg = love.graphics
local real = {
  getDimensions = lg.getDimensions, getWidth = lg.getWidth, getHeight = lg.getHeight,
  setCanvas = lg.setCanvas, newCanvas = lg.newCanvas,
  mouseGetPosition = love.mouse.getPosition, mouseGetX = love.mouse.getX, mouseGetY = love.mouse.getY,
}

function jr.layout()
  local sw, sh = real.getDimensions()
  local s = math.min(sw / jr.dw, sh / jr.dh)
  if jr.integer and s >= 1 then s = math.floor(s) end
  jr.sw, jr.sh, jr.scale = sw, sh, s
  jr.ox = math.floor((sw - jr.dw * s) / 2)
  jr.oy = math.floor((sh - jr.dh * s) / 2)
end

function jr.toVirtual(x, y) return (x - jr.ox) / jr.scale, (y - jr.oy) / jr.scale end

function jr.install()
  jr.layout()
  jr.canvas = real.newCanvas(jr.dw, jr.dh)
  jr.canvas:setFilter(jr.integer and "nearest" or "linear", jr.integer and "nearest" or "linear")
  lg.getDimensions = function() return jr.dw, jr.dh end
  lg.getWidth = function() return jr.dw end
  lg.getHeight = function() return jr.dh end
  -- A game that resets to the screen with setCanvas() lands on ours instead.
  lg.setCanvas = function(c, ...)
    if c == nil and jr.drawing then return real.setCanvas(jr.canvas) end
    return real.setCanvas(c, ...)
  end
  love.mouse.getPosition = function()
    if jr.vmouse then return jr.mx, jr.my end
    return jr.toVirtual(real.mouseGetPosition())
  end
  love.mouse.getX = function() return (love.mouse.getPosition()) end
  love.mouse.getY = function() local _, y = love.mouse.getPosition(); return y end

  local game = { draw = love.draw, update = love.update, resize = love.resize,
    mousepressed = love.mousepressed, mousereleased = love.mousereleased, mousemoved = love.mousemoved,
    touchpressed = love.touchpressed, touchreleased = love.touchreleased, touchmoved = love.touchmoved,
    keypressed = love.keypressed, keyreleased = love.keyreleased, gamepadpressed = love.gamepadpressed,
    gamepadreleased = love.gamepadreleased }
  jr.game = game

  love.resize = function(w, h) jr.layout(); if game.resize then game.resize(jr.dw, jr.dh) end end
  love.update = function(dt)
    for _, h in ipairs(jr.hooks) do if h.update then h.update(dt) end end
    if game.update then game.update(dt) end
  end
  love.draw = function()
    jr.drawing = true
    real.setCanvas(jr.canvas)
    lg.clear(0, 0, 0, 1)
    if game.draw then game.draw() end
    for _, h in ipairs(jr.hooks) do if h.drawVirtual then h.drawVirtual() end end
    jr.drawing = false
    real.setCanvas()
    lg.clear(0, 0, 0, 1)
    lg.setColor(1, 1, 1, 1)
    lg.draw(jr.canvas, jr.ox, jr.oy, 0, jr.scale, jr.scale)
    for _, h in ipairs(jr.hooks) do if h.drawScreen then h.drawScreen() end end
  end
  love.mousepressed = function(x, y, b, t, n)
    if jr.vmouse and not t then return end
    if game.mousepressed then local vx, vy = jr.toVirtual(x, y); game.mousepressed(vx, vy, b, t, n) end
  end
  love.mousereleased = function(x, y, b, t, n)
    if jr.vmouse and not t then return end
    if game.mousereleased then local vx, vy = jr.toVirtual(x, y); game.mousereleased(vx, vy, b, t, n) end
  end
  love.mousemoved = function(x, y, dx, dy, t)
    if jr.vmouse and not t then return end
    if game.mousemoved then local vx, vy = jr.toVirtual(x, y); game.mousemoved(vx, vy, dx / jr.scale, dy / jr.scale, t) end
  end
  local function touchToVirtual(x, y)
    local vx, vy = jr.toVirtual(x * jr.sw, y * jr.sh)
    return vx / jr.dw, vy / jr.dh
  end
  for _, name in ipairs({ "touchpressed", "touchreleased", "touchmoved" }) do
    love[name] = function(id, x, y, dx, dy, p)
      for _, h in ipairs(jr.hooks) do if h[name] and h[name](id, x * jr.sw, y * jr.sh) then return end end
      if game[name] then local vx, vy = touchToVirtual(x, y); game[name](id, vx, vy, dx, dy, p) end
    end
  end
  love.keypressed = function(k, s, r)
    for _, h in ipairs(jr.hooks) do if h.keypressed and h.keypressed(k) then return end end
    if game.keypressed then game.keypressed(k, s, r) end
  end
  love.gamepadpressed = function(j, b)
    for _, h in ipairs(jr.hooks) do if h.gamepadpressed and h.gamepadpressed(j, b) then end end
    if game.gamepadpressed then game.gamepadpressed(j, b) end
  end
  love.gamepadreleased = function(j, b)
    for _, h in ipairs(jr.hooks) do if h.gamepadreleased then h.gamepadreleased(j, b) end end
    if game.gamepadreleased then game.gamepadreleased(j, b) end
  end
  for _, h in ipairs(jr.hooks) do if h.install then h.install() end end
end
"#;

const PORTMASTER: &str = r#"
-- PortMaster: Select + Start quits; a right-stick cursor stands in for the mouse.
do
  local hook = {}
  local down = {}
  function hook.gamepadpressed(j, b)
    if (b == "start" and j:isGamepadDown("back")) or (b == "back" and j:isGamepadDown("start")) then love.event.quit() end
    if jr.vmouse then
      local btn = (b == "rightshoulder" or b == "a") and 1 or ((b == "leftshoulder" or b == "b") and 2 or nil)
      if btn then down[btn] = true; if jr.game.mousepressed then jr.game.mousepressed(jr.mx, jr.my, btn, false, 1) end end
    end
  end
  function hook.gamepadreleased(j, b)
    if jr.vmouse then
      local btn = (b == "rightshoulder" or b == "a") and 1 or ((b == "leftshoulder" or b == "b") and 2 or nil)
      if btn and down[btn] then down[btn] = false; if jr.game.mousereleased then jr.game.mousereleased(jr.mx, jr.my, btn, false, 1) end end
    end
  end
  if @VMOUSE@ then
    jr.vmouse = true
    jr.mx, jr.my = jr.dw / 2, jr.dh / 2
    local speed = jr.dw * 0.6
    function hook.install()
      love.mouse.setVisible = function() end
      love.mouse.isDown = function(...) for _, b in ipairs({ ... }) do if down[b] then return true end end return false end
      real.setVisible = nil
    end
    function hook.update(dt)
      local js = love.joystick.getJoysticks()[1]
      if not (js and js:isGamepad()) then return end
      local ax, ay = js:getGamepadAxis("rightx"), js:getGamepadAxis("righty")
      if math.abs(ax) < 0.2 then ax = 0 end
      if math.abs(ay) < 0.2 then ay = 0 end
      if ax ~= 0 or ay ~= 0 then
        local ox, oy = jr.mx, jr.my
        jr.mx = math.max(0, math.min(jr.dw, jr.mx + ax * speed * dt))
        jr.my = math.max(0, math.min(jr.dh, jr.my + ay * speed * dt))
        if jr.game.mousemoved then jr.game.mousemoved(jr.mx, jr.my, jr.mx - ox, jr.my - oy, false) end
      end
    end
    function hook.drawVirtual()
      love.graphics.setColor(1, 1, 1, 1)
      love.graphics.polygon("fill", jr.mx, jr.my, jr.mx + 10, jr.my + 14, jr.mx + 4, jr.my + 14, jr.mx, jr.my + 20)
      love.graphics.setColor(0, 0, 0, 1)
      love.graphics.polygon("line", jr.mx, jr.my, jr.mx + 10, jr.my + 14, jr.mx + 4, jr.my + 14, jr.mx, jr.my + 20)
    end
  end
  jr.hooks[#jr.hooks + 1] = hook
end
"#;

const TOUCH: &str = r#"
-- Mobile: an on-screen pad that presses the keys the game reads.
do
  local K = { left = @LEFT@, right = @RIGHT@, up = @UP@, down = @DOWN@, a = @A@, b = @B@, start = @START@ }
  local hook = {}
  local held, keysDown = {}, {}
  local function pad()
    local x, y, w, h = 0, 0, jr.sw, jr.sh
    if love.window.getSafeArea then x, y, w, h = love.window.getSafeArea() end
    local u = math.min(w, h) * 0.11
    local cx, cy = x + u * 2.2, y + h - u * 2.4
    local ax, ay = x + w - u * 1.6, y + h - u * 2.2
    return {
      { key = K.left,  shape = "rect", x = cx - u * 1.5, y = cy - u / 2, w = u, h = u },
      { key = K.right, shape = "rect", x = cx + u * 0.5, y = cy - u / 2, w = u, h = u },
      { key = K.up,    shape = "rect", x = cx - u / 2, y = cy - u * 1.5, w = u, h = u },
      { key = K.down,  shape = "rect", x = cx - u / 2, y = cy + u * 0.5, w = u, h = u },
      { key = K.a,     shape = "circle", x = ax, y = ay, r = u * 0.65 },
      { key = K.b,     shape = "circle", x = ax - u * 1.6, y = ay + u * 0.7, r = u * 0.65 },
      { key = K.start, shape = "rect", x = x + w / 2 - u * 0.7, y = y + h - u * 0.9, w = u * 1.4, h = u * 0.6 },
    }
  end
  local function hit(px, py)
    for _, b in ipairs(pad()) do
      if b.shape == "rect" and px >= b.x and px <= b.x + b.w and py >= b.y and py <= b.y + b.h then return b.key end
      if b.shape == "circle" and (px - b.x) ^ 2 + (py - b.y) ^ 2 <= b.r ^ 2 then return b.key end
    end
  end
  local function press(k) if not keysDown[k] then keysDown[k] = true; if jr.game.keypressed then jr.game.keypressed(k, k, false) end end end
  local function release(k) if keysDown[k] then keysDown[k] = nil; if jr.game.keyreleased then jr.game.keyreleased(k, k) end end end
  function hook.install()
    local isDown = love.keyboard.isDown
    love.keyboard.isDown = function(...)
      for _, k in ipairs({ ... }) do if keysDown[k] then return true end end
      return isDown(...)
    end
  end
  hook.touchpressed = function(id, x, y)
    local k = hit(x, y)
    if k then held[id] = k; press(k); return true end
  end
  hook.touchmoved = function(id, x, y)
    if not held[id] then return false end
    local k = hit(x, y)
    if k ~= held[id] then release(held[id]); held[id] = k; if k then press(k) end end
    return true
  end
  hook.touchreleased = function(id)
    if not held[id] then return false end
    release(held[id]); held[id] = nil
    return true
  end
  function hook.drawScreen()
    love.graphics.setLineWidth(2)
    for _, b in ipairs(pad()) do
      love.graphics.setColor(1, 1, 1, keysDown[b.key] and 0.45 or 0.2)
      if b.shape == "rect" then love.graphics.rectangle("fill", b.x, b.y, b.w, b.h, 6, 6) else love.graphics.circle("fill", b.x, b.y, b.r) end
      love.graphics.setColor(1, 1, 1, 0.5)
      if b.shape == "rect" then love.graphics.rectangle("line", b.x, b.y, b.w, b.h, 6, 6) else love.graphics.circle("line", b.x, b.y, b.r) end
    end
    love.graphics.setColor(1, 1, 1, 1)
  end
  jr.hooks[#jr.hooks + 1] = hook
end
"#;

const FINISH: &str = "\nreturn jr\n";

const WEB: &str = r#"
-- Web (love.js): stub what a browser cannot do, so a game that probes for it
-- fails soft instead of crashing.
local jr = { target = "web", hooks = {} }
package.preload["ffi"] = function() error("the ffi library is not available in the browser") end
io.popen = function() return nil, "io.popen is not available in the browser" end
os.execute = function() return nil, "exit", 1 end
if love.thread then
  love.thread.newThread = function() error("love.thread is not available in the browser") end
end
-- Writes are marked so the page can flush its IndexedDB file system.
jr.dirty = false
do
  local fs = love.filesystem
  for _, name in ipairs({ "write", "append", "remove", "createDirectory" }) do
    local real = fs[name]
    if real then fs[name] = function(...) jr.dirty = true; return real(...) end end
  end
end
function jr.install() end
return jr
"#;

/// The PortMaster controller map (`game.gptk`) for gptokeyb2.
pub fn gptk(keys: &std::collections::BTreeSet<String>) -> String {
    let p = PadKeys::from_keys(keys);
    let mut s = String::from("# game.gptk: generated by JoyrIDE from the keys the game reads. Edit freely.\n");
    for (pad, key) in [("up", &p.up), ("down", &p.down), ("left", &p.left), ("right", &p.right)] {
        s.push_str(&format!("{pad} = {key}\n"));
        s.push_str(&format!("left_analog_{pad} = {key}\n"));
    }
    let extra = ["x", "c", "v"].iter().find(|k| **k != p.a && **k != p.b).copied().unwrap_or("c");
    s.push_str(&format!("a = {}\nb = {}\nx = {extra}\ny = v\n", p.a, p.b));
    s.push_str("l1 = lshift\nr1 = tab\nl2 = q\nr2 = e\n");
    s.push_str(&format!("start = {}\nback = escape\n", p.start));
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scan::{scan_sources, Window};
    use std::collections::BTreeSet;

    fn keys(k: &[&str]) -> BTreeSet<String> {
        k.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn pad_keys_follow_the_game() {
        let p = PadKeys::from_keys(&keys(&["left", "right", "space", "escape"]));
        assert_eq!((p.left.as_str(), p.a.as_str(), p.start.as_str()), ("left", "space", "escape"));
        assert_ne!(p.a, p.b);
        let w = PadKeys::from_keys(&keys(&["w", "a", "s", "d", "z"]));
        assert_eq!((w.up.as_str(), w.left.as_str(), w.a.as_str()), ("w", "a", "z"));
        let none = PadKeys::from_keys(&keys(&[]));
        assert_eq!((none.left.as_str(), none.a.as_str(), none.b.as_str(), none.start.as_str()), ("left", "z", "x", "return"));
    }

    #[test]
    fn config_comes_from_the_scan() {
        let scan = scan_sources(&[
            ("conf.lua".into(), "t.window.width = 1280 t.window.height = 720".into()),
            ("main.lua".into(), "function love.keypressed(k) end function love.mousepressed() end".into()),
        ]);
        assert_eq!(scan.window, Window { width: Some(1280.0), height: Some(720.0), ..Default::default() });
        let pm = Config::from_scan(Target::PortMaster, &scan);
        assert!((pm.design_w, pm.design_h, pm.virtual_mouse, pm.integer_scale, pm.touch_overlay) == (1280, 720, true, true, false));
        let m = Config::from_scan(Target::Mobile, &scan);
        assert!(m.touch_overlay && !m.virtual_mouse);
    }

    #[test]
    fn gptk_maps_directions_actions_and_system_keys() {
        let g = gptk(&keys(&["left", "right", "up", "down", "space", "z"]));
        for line in ["up = up", "left_analog_left = left", "a = z", "b = space", "l1 = lshift", "r1 = tab", "start = return", "back = escape"] {
            assert!(g.contains(line), "missing `{line}` in\n{g}");
        }
    }

    #[test]
    fn wrapper_is_the_three_lines_of_the_spec_plus_install() {
        let w = main_wrapper("web");
        assert!(w.contains("require(\"_jr_shim\")") && w.contains("require(\"_orig_main\")") && w.contains("jr.install()"));
    }

    /// Every generated shim is valid LuaJIT (skipped when luajit is absent).
    #[test]
    fn every_shim_compiles() {
        let Some(luajit) = ["/opt/homebrew/bin/luajit", "/usr/local/bin/luajit", "/usr/bin/luajit"].iter().find(|p| std::path::Path::new(p).exists()) else { return };
        let d = tempfile::tempdir().unwrap();
        let base = Config { target: Target::PortMaster, design_w: 640, design_h: 480, integer_scale: true, virtual_mouse: true, touch_overlay: false, pad: PadKeys::from_keys(&keys(&[])) };
        let cases = [
            ("pm_mouse", base.clone()),
            ("pm_plain", Config { virtual_mouse: false, ..base.clone() }),
            ("mobile_touch", Config { target: Target::Mobile, virtual_mouse: false, touch_overlay: true, integer_scale: false, ..base.clone() }),
            ("mobile_plain", Config { target: Target::Mobile, virtual_mouse: false, touch_overlay: false, ..base.clone() }),
            ("web", Config { target: Target::Web, ..base.clone() }),
        ];
        for (name, c) in cases {
            let p = d.path().join(format!("{name}.lua"));
            std::fs::write(&p, generate(&c)).unwrap();
            let out = std::process::Command::new(luajit).args(["-bl"]).arg(&p).output().unwrap();
            assert!(out.status.success(), "{name}: {}", String::from_utf8_lossy(&out.stderr));
        }
    }
}
