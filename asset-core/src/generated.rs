//! Assets made by a deterministic generator (Painter, Composer, Animator):
//! the same recipe, parameters and seed give the same bytes, so a generated
//! asset records those three and can always be made again. Because the bytes
//! are the identity, generating the same thing twice is one asset.
//!
//! The generators themselves are JavaScript (`src/vendor/`) and run in the
//! app's webview or a worker; this module only records what they made.

use crate::catalog::{Catalog, NewAsset};
use crate::kind::Kind;
use crate::licence::Licence;
use crate::{dedup, Result};
use std::path::Path;

#[derive(Debug, Clone)]
pub struct Generated<'a> {
    /// `art-sprites`, `music-composer`, `sprite-animator`.
    pub engine: &'a str,
    /// The engine's version, since a new version may draw differently.
    pub engine_version: &'a str,
    pub recipe: &'a str,
    /// The recipe's parameters as JSON text, in a stable order.
    pub params: &'a str,
    pub seed: &'a str,
    pub kind: Kind,
    pub name: &'a str,
    pub ext: &'a str,
    pub bytes: &'a [u8],
}

impl Generated<'_> {
    /// The line stored as the asset's origin, parseable by [`parse_origin`].
    pub fn origin(&self) -> String {
        format!("{}@{} recipe={} seed={} params={}", self.engine, self.engine_version, self.recipe, self.seed, self.params)
    }
}

/// The licence generated output carries: the engines are the maintainer's, so
/// the output is released as CC0. The person can change it on the record.
pub const GENERATED_LICENCE: &str = "CC0-1.0";

/// Stores generated bytes in the library and records how to make them again.
/// Returns the asset id and whether it was new. Confirmed by the generator:
/// no person had to check where it came from.
pub fn add(cat: &mut Catalog, library_dir: &Path, g: &Generated) -> Result<(i64, bool)> {
    let hash = dedup::hash_bytes(g.bytes);
    let stored = format!("{}/{hash}.{}", &hash[..2], g.ext);
    let dest = library_dir.join(&stored);
    if !dest.exists() {
        std::fs::create_dir_all(dest.parent().unwrap())?;
        let tmp = dest.with_extension("partial");
        std::fs::write(&tmp, g.bytes)?;
        std::fs::rename(&tmp, &dest)?;
    }
    let (id, fresh) = cat.add_asset(&NewAsset { hash, size: g.bytes.len() as u64, kind: g.kind, name: g.name.into(), ext: g.ext.into(), stored })?;
    if fresh {
        cat.confirm_licence(id, &Licence::from_spdx(GENERATED_LICENCE), "generator", &format!("made by {}", g.engine))?;
        cat.add_tag(id, "origin:generated")?;
    }
    cat.record_origin(id, "generator", &g.origin())?;
    Ok((id, fresh))
}

/// A generator origin line taken apart: `(engine, version, recipe, seed, params)`.
pub fn parse_origin(line: &str) -> Option<(String, String, String, String, String)> {
    let (head, rest) = line.split_once(" recipe=")?;
    let (engine, version) = head.split_once('@')?;
    let (recipe, rest) = rest.split_once(" seed=")?;
    let (seed, params) = rest.split_once(" params=")?;
    Some((engine.into(), version.into(), recipe.into(), seed.into(), params.into()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn gen<'a>(bytes: &'a [u8], seed: &'a str) -> Generated<'a> {
        Generated { engine: "art-sprites", engine_version: "1.31.1", recipe: "item", params: "{\"shape\":\"sword\"}", seed, kind: Kind::Image, name: "sword.png", ext: "png", bytes }
    }

    #[test]
    fn generated_assets_are_confirmed_cc0_and_remember_their_recipe() {
        let d = tempfile::tempdir().unwrap();
        let mut c = Catalog::in_memory().unwrap();
        let (id, fresh) = add(&mut c, d.path(), &gen(b"PIXELS", "7")).unwrap();
        assert!(fresh);
        let a = c.get(id).unwrap().unwrap();
        assert!(a.is_usable() && a.licence.as_ref().unwrap().spdx == "CC0-1.0");
        assert!(a.tags.contains(&"origin:generated".to_string()));
        assert_eq!(std::fs::read(d.path().join(&a.stored)).unwrap(), b"PIXELS");
        let (kind, line) = c.origins(id).unwrap().remove(0);
        assert_eq!(kind, "generator");
        assert_eq!(parse_origin(&line).unwrap(), ("art-sprites".into(), "1.31.1".into(), "item".into(), "7".into(), "{\"shape\":\"sword\"}".into()));
    }

    #[test]
    fn making_the_same_thing_twice_is_one_asset_with_one_origin() {
        let d = tempfile::tempdir().unwrap();
        let mut c = Catalog::in_memory().unwrap();
        let (a, _) = add(&mut c, d.path(), &gen(b"PIXELS", "7")).unwrap();
        let (b, fresh) = add(&mut c, d.path(), &gen(b"PIXELS", "7")).unwrap();
        assert_eq!((a, fresh), (b, false));
        assert_eq!(c.origins(a).unwrap().len(), 1);
        // A different seed that happens to give the same pixels adds a second way to make it.
        add(&mut c, d.path(), &gen(b"PIXELS", "8")).unwrap();
        assert_eq!(c.origins(a).unwrap().len(), 2);
    }

    #[test]
    fn origin_lines_survive_odd_params() {
        let g = Generated { params: "{\"a\":\"x y=z seed=9\"}", ..gen(b"x", "1") };
        let back = parse_origin(&g.origin()).unwrap();
        assert_eq!(back.2, "item");
        assert_eq!(back.3, "1");
        assert!(parse_origin("not an origin").is_none());
    }
}
